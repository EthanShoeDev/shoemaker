// Prebuilt bun release archives for the version in `packageManager`
// (package-json.ts) and the CI setup action. nixpkgs lags bun releases, so
// the flake swaps the source; bump all three together.
const BUN_VERSION = '1.4.4';
const BUN_SOURCES = [
  [
    'aarch64-darwin',
    'darwin-aarch64',
    'sha256-wkDX8My5DCY6hJ/NsJt+5iYw2SE0jtaq/ahrnVd7xRA=',
  ],
  [
    'x86_64-darwin',
    'darwin-x64',
    'sha256-UKNJH3Orwv6BZzFxqFdi07wswWgMzsrdmD3pmt93l34=',
  ],
  [
    'aarch64-linux',
    'linux-aarch64',
    'sha256-uqa7NvUdblhWHgK76oJQOKnfRU9nPW13bou/hvjHhQ4=',
  ],
  [
    'x86_64-linux',
    'linux-x64',
    'sha256-v4zL+ysLgBWeD5ptFcVTF63YB3U028YTCj7bUvzLOVw=',
  ],
] as const;

// A `#` region whose markers sit at the indentation of the body.
const nixRegion = (id: string, body: string, pad: string) =>
  Arr.join(
    [`${pad}# shoemaker:begin ${id}`, body, `${pad}# shoemaker:end ${id}`],
    '\n',
  );

const bunOverlay = () => {
  const sources = pipe(
    BUN_SOURCES,
    Arr.map(
      ([system, archive, hash]) => `              "${system}" = prev.fetchurl {
                url = "https://github.com/oven-sh/bun/releases/download/bun-v\${finalAttrs.version}/bun-${archive}.zip";
                hash = "${hash}";
              };`,
    ),
    Arr.join('\n'),
  );
  return `    # nixpkgs lags bun releases, so repoint the prebuilt release archives at
    # the version in package.json \`packageManager\` and the CI setup action.
    # bun ships binaries only, so this is a src swap and nothing is compiled.
    # Keep the three in lockstep.
    bunOverlay = _final: prev: {
      bun = prev.bun.overrideAttrs (finalAttrs: oldAttrs: {
        version = "${BUN_VERSION}";
        __intentionallyOverridingVersion = true;
        passthru =
          oldAttrs.passthru
          // {
            sources = {
${sources}
            };
          };
      });
    };`;
};

// Expo apps build for Android in their own dev shell, so the default shell
// never pulls the SDK.
export const hasAndroid = (config: ShoemakerConfig) => hasApp(config, 'expo');

const ANDROID_INPUTS = `
  inputs = {
    nixpkgs.url = "github:nixos/nixpkgs/nixpkgs-unstable";
    # The Android SDK of the \`android\` dev shell (nix/android.nix).
    android-nixpkgs = {
      url = "github:tadfisher/android-nixpkgs";
      inputs.nixpkgs.follows = "nixpkgs";
    };
  };

  # Android SDK packages from android-nixpkgs' binary cache instead of
  # Google's servers. Nix asks once whether to trust it.
  nixConfig = {
    extra-substituters = ["https://android-nixpkgs.cachix.org"];
    extra-trusted-public-keys = [
      "android-nixpkgs.cachix.org-1:2lZoPmwoyTVGaNDHqa6A32tdn8Gc0aMWBRrfXN1H3dQ="
    ];
  };
`;

// Google licenses the SDK packages (sdkmanager, platforms, NDK) as unfree.
const ANDROID_UNFREE = `
            # The Android SDK is unfree (Google's license).
            config.allowUnfree = true;`;

const ANDROID_SHELL = `

      # \`nix develop .#android\`: the default shell plus the Android SDK, NDK
      # and JDK that Expo's Gradle builds need.
      android = import ./nix/android.nix {inherit pkgs default;};`;

const { platform, buildTools, agpBuildTools, ndk, cmake } = androidToolchain;
const dashed = (version: string) => Str.replaceAll('.', '-')(version);

// Owned, so a toolchain bump reaches every repo through sync; flake.nix only
// imports it.
const androidNix = `# Generated by shoemaker; \`shoemaker sync\` rewrites this file.
# The Android toolchain for the repo's Expo apps, matching what the Expo SDK's
# React Native builds with. Gradle downloads no SDK packages: everything it
# needs is here.
{
  pkgs,
  default,
}: let
  packages = pkgs.androidSdk (p:
    with p; [
      cmdline-tools-latest
      platform-tools
      ${platform}
      build-tools-${dashed(buildTools)}
      build-tools-${dashed(agpBuildTools)}
      ndk-${dashed(ndk)}
      cmake-${dashed(cmake)}
    ]);
  # Google's prebuilt ninja segfaults on nixpkgs' glibc, so the CMake that
  # Gradle runs builds with nixpkgs' ninja. symlinkJoin keeps the first path's
  # file where two collide.
  ninja = pkgs.runCommand "android-cmake-ninja" {} ''
    mkdir -p $out/share/android-sdk/cmake/${cmake}/bin
    ln -s \${pkgs.ninja}/bin/ninja $out/share/android-sdk/cmake/${cmake}/bin/ninja
  '';
  sdk = pkgs.symlinkJoin {
    name = "android-sdk";
    paths = [ninja packages];
  };
  root = "\${sdk}/share/android-sdk";
in
  pkgs.mkShell {
    inputsFrom = [default];
    packages = [sdk pkgs.jdk17];
    shellHook = ''
      export ANDROID_HOME="\${root}"
      export ANDROID_SDK_ROOT="\${root}"
      export ANDROID_NDK_ROOT="\${root}/ndk/${ndk}"
      export ANDROID_NDK_HOME="$ANDROID_NDK_ROOT"
      export JAVA_HOME="\${pkgs.jdk17.home}"
      export PATH="\${root}/platform-tools:\${root}/cmdline-tools/latest/bin:$PATH"
      # Gradle's aapt2 from Maven is a dynamically linked binary NixOS cannot
      # run, and the store is read-only: use the SDK's aapt2, download nothing.
      export GRADLE_OPTS="-Dorg.gradle.project.android.aapt2FromMavenOverride=\${root}/build-tools/${buildTools}/aapt2 -Dorg.gradle.project.android.builder.sdkDownload=false"
    '';
  }
`;

export const flake: Renderer = (ctx, aggregate) => {
  const packages = [
    ...new Set([
      'bun',
      'nodejs_24',
      ...aggregate.nixPackages,
      ...ctx.config.nixPackages,
    ]),
  ];
  const description =
    ctx.config.description === ''
      ? ctx.config.name
      : `${ctx.config.name}: ${ctx.config.description}`;
  const android = hasAndroid(ctx.config);
  const content = `{
  description = ${JSON.stringify(description)};
${android ? ANDROID_INPUTS : '\n  inputs.nixpkgs.url = "github:nixos/nixpkgs/nixpkgs-unstable";\n'}
  outputs = ${android ? '{\n    nixpkgs,\n    android-nixpkgs,\n    ...\n  }' : '{nixpkgs, ...}'}: let
${nixRegion('bun', bunOverlay(), '    ')}
    forAllSystems = function:
      nixpkgs.lib.genAttrs nixpkgs.lib.systems.flakeExposed (
        system:
          function (import nixpkgs {
            inherit system;
            overlays = [bunOverlay${android ? ' android-nixpkgs.overlays.default' : ''}];${android ? ANDROID_UNFREE : ''}
          })
      );
  in {
    formatter = forAllSystems (pkgs: pkgs.alejandra);

    devShells = forAllSystems (pkgs: ${android ? 'rec ' : ''}{
      default = pkgs.mkShell {
        packages = with pkgs; [
${nixRegion(
  'packages',
  Arr.join(
    Arr.map(packages, (p) => `          ${p}`),
    '\n',
  ),
  '          ',
)}
          # Project packages go below the region.
        ];
        shellHook = ''
${nixRegion('shell-hook', '          export TZ=UTC', '          ')}
        '';
      };${android ? ANDROID_SHELL : ''}
    });
  };
}
`;
  return [managed('flake.nix', content)];
};

// What `nix flake lock` writes for the flake's inputs, pinned so a new repo is
// locked (and committed) before any nix command runs. Seeded: `nix flake
// update` owns it from then on.
const nixpkgsNode = {
  locked: {
    lastModified: nixpkgsLock.lastModified,
    narHash: nixpkgsLock.narHash,
    owner: 'nixos',
    repo: 'nixpkgs',
    rev: nixpkgsLock.rev,
    type: 'github',
  },
  original: {
    owner: 'nixos',
    ref: 'nixpkgs-unstable',
    repo: 'nixpkgs',
    type: 'github',
  },
};

const sortKeys = (nodes: Readonly<Record<string, unknown>>) =>
  Rec.fromEntries(
    Arr.map(
      Arr.sort(Rec.keys(nodes), Str.Order),
      (key) => [key, nodes[key]] as const,
    ),
  );

const flakeLock = (android: boolean) =>
  `${JSON.stringify(
    {
      // Keys sorted, as nix writes them.
      nodes: sortKeys(
        android
          ? {
              ...androidLockNodes,
              nixpkgs: nixpkgsNode,
              root: {
                inputs: {
                  'android-nixpkgs': 'android-nixpkgs',
                  nixpkgs: 'nixpkgs',
                },
              },
            }
          : { nixpkgs: nixpkgsNode, root: { inputs: { nixpkgs: 'nixpkgs' } } },
      ),
      root: 'root',
      version: 7,
    },
    null,
    2,
  )}\n`;

export const nixFiles: Generator = (ctx) => ({
  files: [
    owned('.envrc', 'use flake\n'),
    seed('flake.lock', flakeLock(hasAndroid(ctx.config))),
    ...(hasAndroid(ctx.config) ? [owned('nix/android.nix', androidNix)] : []),
  ],
  gitignore: ['.direnv', 'result', 'result-*'],
});
