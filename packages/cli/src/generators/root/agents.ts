import type { ShoeboxConfig } from '../../config/schema.ts';
import type { Generator } from '../../engine/types.ts';
import { json, managed, owned, region, seed } from '../shared.ts';

const verifyCommand = (config: ShoeboxConfig) =>
  config.taskRunner === 'nx'
    ? 'bunx nx run-many -t lint:check typecheck -p <affected-package>'
    : 'bunx turbo lint:check typecheck --filter=<affected-package>';

const workflow = (config: ShoeboxConfig) => `## Workflow

- Work in focused, reviewable steps. Do not silently expand the current task
  into a broader refactor.
- Never use \`git stash\` without the user's permission.
- Never run \`infra:plan\`, \`infra:deploy\` or \`infra:destroy\` without the
  user's permission: alchemy creates its state store even on a plan, and local
  cloud credentials make that real.
- Before creating a pull request or declaring a code-changing task complete,
  run lint and typecheck on each affected package:

  \`\`\`sh
  ${verifyCommand(config)}
  \`\`\`

- Do not rerun lint and typecheck after every intermediate edit.
- Use \`lint:check\` for verification. \`lint\` runs fixers and may modify the
  working tree; run it only when intentionally applying fixes.
- Use \`bun run test\` to invoke Vitest. Do not use \`bun test\`, which runs
  Bun's built-in test runner instead.

## Bun

Bun is the only package manager. Use \`bun install\`, \`bun run <script>\`,
\`bunx\`, and \`bun <file>\`; never npm, yarn, pnpm, npx, or ts-node. Every
dependency version lives in the root \`workspaces.catalog\`; packages depend on
\`catalog:\` (\`bun run catalog:check\` enforces it).`;

const codeStyle = (config: ShoeboxConfig) => `## Code style

- Prefer concise, simple solutions. Propose a simpler approach when one exists.
- Prefer inferred TypeScript types. Do not add return types or annotations the
  compiler can infer.
- Comments only for a non-obvious *why*. Lint directives and the reason text a
  lint rule requires are the exception.
- Every \`oxlint-disable\` directive needs a description:
  \`// oxlint-disable-next-line <rule> -- <reason>\`.
- Zero warnings: rules are \`error\` or \`off\`, and every rule change in
  \`oxlint.config.ts\` carries a one-line reason above it.

## Effect

- Effect v4 everywhere. Write effectful functions with \`Effect.fn\`, model
  failures as tagged errors, and log with \`Effect.log\`, not \`console\`.
- Tests use \`@effect/vitest\`: \`it.effect\` with \`assert\`.
- Time comes from \`Clock\` (and \`TestClock\` in tests), never \`Date.now()\`.
- Configuration comes from Effect \`Config\` through \`@${config.scope}/env\`, never
  \`process.env\` (the \`no-raw-env-access\` lint rule enforces it).`;

const tooling = `## Tooling

Repo tooling (lint, format, tsconfig, task graph, CI, nix shell, this file's
shoebox regions) is generated by \`shoebox\` from \`shoebox.config.ts\`. To change
or update it, edit \`shoebox.config.ts\` or bump \`@shoe-box-tools/*\`, then run
\`bun run shoebox:sync\`. Do not hand-edit text between \`shoebox:begin\` and
\`shoebox:end\` markers: the next sync rewrites it.

## Guidelines

Task-specific guidance lives in \`docs/guidelines/\`. Read the index
\`docs/guidelines/README.md\` first, then only the files relevant to the task.
Keep the index in sync when adding, renaming, or removing a guideline.`;

const agentsMd = (config: ShoeboxConfig) => `# AGENTS.md

This is the canonical instruction file for every coding agent working in this
repository. \`CLAUDE.md\` imports it; do not duplicate rules there.

${region('workflow', workflow(config), '<!--')}

${region('code-style', codeStyle(config), '<!--')}

${region('tooling', tooling, '<!--')}

## Project notes

Project-specific rules go here; shoebox never touches this section.
`;

const runnerPermission = (config: ShoeboxConfig) =>
  config.taskRunner === 'nx' ? 'Bash(bunx nx:*)' : 'Bash(bunx turbo:*)';

const GUIDELINES = `# Guidelines

Task-specific guidance for agents and humans. Read this index, then only the
guidelines relevant to the task.

| Guideline | When to read |
| --------- | ------------ |
`;

export const agentFiles: Generator = (ctx) =>
  ctx.config.features.agents
    ? {
        files: [
          managed('AGENTS.md', agentsMd(ctx.config)),
          owned('CLAUDE.md', '@AGENTS.md\n'),
          seed(
            '.claude/settings.json',
            json({
              permissions: {
                allow: [
                  'Bash(bun install:*)',
                  'Bash(bun run:*)',
                  runnerPermission(ctx.config),
                  'Bash(bunx vitest:*)',
                  'Bash(bunx tsc:*)',
                  'Bash(bunx oxlint:*)',
                  'Bash(bunx oxfmt:*)',
                  'Bash(bunx knip:*)',
                ],
              },
            }),
          ),
          seed('docs/guidelines/README.md', GUIDELINES),
        ],
      }
    : {};
