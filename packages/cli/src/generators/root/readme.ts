import { Array as Arr } from 'effect';

import type { ShoemakerConfig } from '../../config/schema.ts';
import type { Generator } from '../../engine/types.ts';
import { seed } from '../shared.ts';

const run = (config: ShoemakerConfig, args: string) =>
  config.taskRunner === 'nx'
    ? `bunx nx run-many -t ${args}`
    : `bunx turbo run ${args}`;

const secretsLine = (config: ShoemakerConfig) => {
  switch (config.secrets) {
    case 'varlock': {
      return '- Env: varlock (`.env.schema`), read through `ENV` from `varlock/env`\n';
    }
    case 'secretspec': {
      return '- Env: secretspec (`secretspec.toml`)\n';
    }
    case 'none': {
      return '';
    }
  }
};

const readme = (config: ShoemakerConfig) => `# ${config.name}

${config.description === '' ? 'TODO: describe the project.' : config.description}

## Stack

- bun workspaces (\`apps/*\`, \`packages/*\`), every dependency pinned in the root catalog
- Effect v4, TypeScript 7 (\`tsc --noEmit\`)
- ${config.taskRunner} for the task graph
- oxlint (type-aware) + oxfmt, jscpd, knip
- vitest with \`@effect/vitest\`
${secretsLine(config)}- Nix dev shell (\`direnv allow\` or \`nix develop\`)
${
  config.apps.length === 0
    ? ''
    : `\n## Apps\n\n${Arr.join(
        Arr.map(config.apps, (app) => `- \`apps/${app.name}\` (${app.kind})`),
        '\n',
      )}\n`
}
## Commands

\`\`\`sh
bun install
${run(config, 'dev')}               # every app in dev mode
bun run test                         # all tests (never \`bun test\`)
${run(config, 'lint:check')}        # lint + typecheck, no writes
${run(config, 'lint')}              # apply lint and format fixes
bun run shoemaker:sync                 # update generated tooling
\`\`\`

Tooling is generated by [shoemaker](https://github.com/EthanShoeDev/shoemaker)
from \`shoemaker.config.ts\`.
`;

export const readmeFile: Generator = (ctx) => ({
  files: [seed('README.md', readme(ctx.config))],
});
