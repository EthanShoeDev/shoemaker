import { appDir } from './common.ts';

// Opted-in Expo apps (`androidRelease`) ship every changesets release as a
// GitHub Release carrying a signed APK. Obtainium's GitHub source installs
// the newest release with an `.apk` asset and reads its version from the tag,
// so the tag, `versionName` and an ever-growing `versionCode` must agree, and
// every APK must be signed with the same upload key.

export const releasingApps = (ctx: GenContext) =>
  Arr.filter(
    ctx.config.apps,
    (app): app is App & { readonly androidRelease: AndroidRelease } =>
      app.kind === 'expo' && app.androidRelease !== undefined,
  );

const envPrefix = (app: App) =>
  `${Str.toUpperCase(Str.replaceAll('-', '_')(app.name))}_ANDROID`;

const signingKeys = (app: App) => {
  const prefix = envPrefix(app);
  return {
    keystore: `${prefix}_KEYSTORE_BASE64`,
    password: `${prefix}_KEYSTORE_PASSWORD`,
    alias: `${prefix}_KEY_ALIAS`,
  };
};

// Release builds need all three; they stay optional so every other command
// runs without them, and the Gradle build fails when they are missing.
const signingEnv = (app: App): ReadonlyArray<EnvVar> => {
  const keys = signingKeys(app);
  return [
    {
      key: keys.keystore,
      description: `Base64 of ${app.name}'s Android upload keystore; signs every release APK`,
      required: false,
      sensitive: true,
      tags: [app.name],
    },
    {
      key: keys.password,
      description: `Password of ${app.name}'s Android upload keystore and its key`,
      required: false,
      sensitive: true,
      tags: [app.name],
    },
    {
      key: keys.alias,
      description: `Alias of the upload key in ${app.name}'s Android keystore`,
      required: false,
      sensitive: false,
      tags: [app.name],
    },
  ];
};

// Appended to the prebuilt android/app/build.gradle. A second `android {}`
// block configures the same extension, so nothing in Expo's template has to
// be matched or rewritten. Without the key a release build fails instead of
// falling back to the debug key, which Android would refuse to update over.
const signingGradle = (app: App) => {
  const keys = signingKeys(app);
  return `
// shoemaker:android-release
def uploadKeystore = System.getenv('${keys.keystore}')
android {
    signingConfigs {
        upload {
            if (uploadKeystore) {
                def keystoreFile = layout.buildDirectory.file('upload.keystore').get().asFile
                keystoreFile.parentFile.mkdirs()
                keystoreFile.bytes = java.util.Base64.mimeDecoder.decode(uploadKeystore)
                storeFile keystoreFile
                storePassword System.getenv('${keys.password}')
                keyAlias System.getenv('${keys.alias}')
                keyPassword System.getenv('${keys.password}')
            }
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.upload
        }
    }
}
gradle.taskGraph.whenReady { graph ->
    if (!uploadKeystore && graph.allTasks.any { it.project == project && it.name == 'packageRelease' }) {
        throw new GradleException('${keys.keystore} is not set: release builds are signed with the upload key')
    }
}
`;
};

export const androidReleaseSource = (
  app: App,
  release: AndroidRelease,
) => `// Generated by shoemaker; \`shoemaker sync\` rewrites this file. app.config.ts
// wraps its config in \`withAndroidRelease\`.
import type { ExpoConfig } from 'expo/config';
import { withAppBuildGradle } from 'expo/config-plugins';

import manifest from './package.json' with { type: 'json' };

const SIGNING = \`${signingGradle(app)}\`;

// Android only updates an app over a lower versionCode, so it grows with the
// changesets version: 1.2.3 is 1_002_003.
const versionCode = (version: string) => {
  const [, major = '', minor = '', patch = ''] =
    /^(\\d+)\\.(\\d+)\\.(\\d+)/u.exec(version) ?? [];
  if (major === '' || Number(minor) > 999 || Number(patch) > 999) {
    throw new Error(\`package.json version \${version} has no versionCode\`);
  }
  return Math.max(
    1,
    Number(major) * 1_000_000 + Number(minor) * 1000 + Number(patch),
  );
};

const withUploadSigning = (config: ExpoConfig) =>
  withAppBuildGradle(config, (mod) =>
    /shoemaker:android-release/u.test(mod.modResults.contents)
      ? mod
      : {
          ...mod,
          modResults: {
            ...mod.modResults,
            contents: \`\${mod.modResults.contents}\${SIGNING}\`,
          },
        },
  );

// The package.json version (which changesets bumps) becomes versionName and
// versionCode, so a release tag, the installed app and Obtainium agree.
export const withAndroidRelease = (config: ExpoConfig) =>
  withUploadSigning({
    ...config,
    version: manifest.version,
    android: {
      ...config.android,
      package: '${release.package}',
      versionCode: versionCode(manifest.version),
    },
  });
`;

// `build:apk` reads the signing key from the environment (GitHub secrets in
// CI); the root `apk:<app>` script loads it through the secrets manager. Both
// run in the flake's `android` dev shell, which carries the SDK.
export const apkScript =
  'expo prebuild --platform android --clean --no-install && cd android && ./gradlew assembleRelease';

export const APK_PATH = 'android/app/build/outputs/apk/release/app-release.apk';

const secretsHome = (ctx: GenContext) => {
  switch (ctx.config.secrets) {
    case 'varlock': {
      return '`.env.local` (or a varlock plugin)';
    }
    case 'secretspec': {
      return "secretspec's `production` profile";
    }
    case 'none': {
      return "your shell's environment";
    }
  }
};

export const androidReleaseReadme = (ctx: GenContext, app: App) => {
  const keys = signingKeys(app);
  return `
## Android releases

Every changesets release of this app becomes a GitHub Release with a signed
APK. To install and update it with [Obtainium](https://obtainium.imranr.dev),
add \`https://github.com/EthanShoeDev/${ctx.config.name}\`. When the repo
releases more than one app, also set "Filter release titles by regEx" to
\`^${ctx.pkg(app.name)}@\`.

Every APK must be signed with the same upload key, or Android refuses the
update, so create it once and keep it:

\`\`\`sh
keytool -genkeypair -v -storetype PKCS12 -keystore upload.keystore \\
  -alias upload -keyalg RSA -keysize 2048 -validity 10000
base64 -w0 upload.keystore
\`\`\`

| Variable | Value |
| --- | --- |
| \`${keys.keystore}\` | the base64 above |
| \`${keys.password}\` | the keystore password |
| \`${keys.alias}\` | \`upload\` |

Set them as GitHub Actions secrets for the release workflow, and in
${secretsHome(ctx)} for \`bun run apk:${app.name}\`. That builds the same APK
locally, in the flake's \`android\` dev shell, which brings the Android SDK.
`;
};

export const androidRelease = (
  ctx: GenContext,
  app: App,
  release: AndroidRelease,
): Contribution => {
  const dir = appDir(app);
  return {
    files: [
      owned(`${dir}/android-release.ts`, androidReleaseSource(app, release)),
      {
        path: 'package.json',
        strategy: 'json-merge',
        content: `${JSON.stringify({
          scripts: {
            [`apk:${app.name}`]: `nix develop .#android --command ${withSecrets(
              ctx.config,
              `bun run --cwd ${dir} build:apk`,
              'production',
            )}`,
          },
        })}\n`,
      },
    ],
    env: signingEnv(app),
    gitignore: [`${dir}/android/`],
  };
};

const expr = (body: string) => `\${{ ${body} }}`;

const versionOutputs = (apps: ReadonlyArray<App>) =>
  Arr.join(
    Arr.map(
      apps,
      (app) => `      ${app.name}: ${expr(`steps.tags.outputs.${app.name}`)}`,
    ),
    '\n',
  );

const tagLines = (ctx: GenContext, apps: ReadonlyArray<App>) =>
  Arr.join(
    Arr.map(
      apps,
      (app) =>
        `          echo "${app.name}=$(jq -r '.[] | select(.name == "${ctx.pkg(app.name)}") | "\\(.name)@\\(.version)"' <<<"$PUBLISHED")" >> "$GITHUB_OUTPUT"`,
    ),
    '\n',
  );

const androidJob = (app: App) => {
  const dir = appDir(app);
  const keys = signingKeys(app);
  const tag = `needs.version.outputs.${app.name}`;
  const secret = (key: string) => `          ${key}: ${expr(`secrets.${key}`)}`;
  return `
  android-${app.name}:
    needs: version
    if: ${tag} != ''
    runs-on: ubuntu-latest
    timeout-minutes: 45
    permissions:
      contents: write
    steps:
      - uses: actions/checkout@v7
        with:
          ref: ${expr(tag)}
      - uses: ./.github/actions/setup
      # The same \`android\` dev shell (nix/android.nix) a local
      # \`bun run apk:${app.name}\` builds in.
      - uses: DeterminateSystems/nix-installer-action@v22
        with:
          # Upstream Nix: Determinate's default also logs in to FlakeHub,
          # which nothing here uses.
          determinate: false
          # Takes the flake's android-nixpkgs binary cache.
          extra-conf: |
            accept-flake-config = true
      - name: Build the signed APK
        run: nix develop .#android --command bun run --cwd ${dir} build:apk
        env:
${Arr.join(Arr.map([keys.keystore, keys.password, keys.alias], secret), '\n')}
      # Created only now, with the APK attached, so Obtainium never sees a
      # release without one. A prerelease version stays out of its default feed.
      - name: Publish the GitHub Release
        env:
          GH_TOKEN: ${expr('github.token')}
          TAG: ${expr(tag)}
        run: |
          version="\${TAG##*@}"
          apk="${app.name}-$version.apk"
          cp ${dir}/${APK_PATH} "$apk"
          touch notes.md
          if [[ -f ${dir}/CHANGELOG.md ]]; then
            awk -v heading="## $version" '$0 == heading { found = 1; next } found && /^## / { exit } found' ${dir}/CHANGELOG.md > notes.md
          fi
          flags=()
          if [[ "$version" == *-* ]]; then flags+=(--prerelease); fi
          gh release create "$TAG" "$apk" --title "$TAG" --notes-file notes.md "\${flags[@]}"
`;
};

export const releaseWorkflow = (
  ctx: GenContext,
  apps: ReadonlyArray<App>,
) => `name: Release

# Pending changesets keep a "chore: version packages" PR open. Merging it tags
# every bumped package, and each Android app released gets a GitHub Release
# with its signed APK: the feed Obtainium installs and updates from.
on:
  push:
    branches: [main]

concurrency:
  group: release
  cancel-in-progress: false

jobs:
  version:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: write
      pull-requests: write
    outputs:
${versionOutputs(apps)}
    steps:
      - uses: actions/checkout@v7
      - uses: ./.github/actions/setup
      # The APK builds run in this workflow because tags pushed with
      # GITHUB_TOKEN start no other workflow. v2 is the line for Changesets 3:
      # it reads what \`changeset git-tag\` tagged from CHANGESETS_OUTPUT.
      - id: changesets
        uses: changesets/action@v2
        with:
          version-script: bun run changeset:version
          publish-script: bunx changeset git-tag
          commit-message: 'chore: version packages'
          pr-title: 'chore: version packages'
          create-github-releases: false
      - id: tags
        if: steps.changesets.outputs.published == 'true'
        env:
          PUBLISHED: ${expr("steps.changesets.outputs['published-packages']")}
        run: |
${tagLines(ctx, apps)}
${Arr.join(Arr.map(apps, androidJob), '')}`;

export const releaseGenerator: Generator = (ctx) => {
  const apps = releasingApps(ctx);
  return apps.length === 0 || ctx.config.ci !== 'github'
    ? {}
    : {
        files: [
          owned('.github/workflows/release.yml', releaseWorkflow(ctx, apps)),
        ],
      };
};
