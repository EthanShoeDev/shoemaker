import { Array as Arr } from 'effect';

import { type App, hasTheme } from '../../config/schema.ts';
import type { Contribution, GenContext } from '../../engine/types.ts';
import { owned, ownedJson, seed, workspacePackageJson } from '../shared.ts';
import {
  appDir,
  catalogOf,
  forApps,
  mergeContributions,
  toolchainDevDependencies,
  vitestConfig,
} from './common.ts';
import {
  androidRelease,
  androidReleaseReadme,
  apkScript,
} from './expo-release.ts';
import { appStylesheet, themeDependency } from './theme.ts';

// expo-router's required peers for a JS-only app; `expo install --fix` owns
// the exact native versions within the SDK.
const dependencies = [
  'expo',
  'expo-constants',
  'expo-linking',
  'expo-router',
  // Applies `userInterfaceStyle` on Android.
  'expo-system-ui',
  'react',
  'react-native',
  'react-native-safe-area-context',
  'react-native-screens',
  // Tailwind classes on React Native components, compiled by Metro.
  'uniwind',
];
const devDependencies = [
  ...toolchainDevDependencies,
  '@types/react',
  'tailwindcss',
];

// With `androidRelease`, android-release.ts sets the version from
// package.json, so the seed leaves it out.
const appConfig = (app: App) => {
  const release = app.androidRelease !== undefined;
  return `import type { ExpoConfig } from 'expo/config';
${release ? "\nimport { withAndroidRelease } from './android-release.ts';\n" : ''}
const config: ExpoConfig = {
  name: '${app.name}',
  slug: '${app.name}',
  scheme: '${app.name}',${release ? '' : "\n  version: '0.0.0',"}
  orientation: 'portrait',
  userInterfaceStyle: 'automatic',
  // OTA updates need expo-updates and an EAS project; turn this on with both.
  updates: { enabled: false },
  plugins: ['expo-router'],
  experiments: { typedRoutes: true },
};
${
  release
    ? `
// Versions the app from package.json and signs Android release builds.
export default withAndroidRelease(config);
`
    : `
export default config;
`
}`;
};

// Expo compiles TS metro configs to CommonJS, so \`__dirname\` (not
// \`import.meta\`) is what exists at load time. The default config already
// handles bun workspaces and package exports.
const metroConfig = `import { getDefaultConfig } from 'expo/metro-config';
import { withUniwindConfig } from 'uniwind/metro';

// Uniwind wraps the finished config: it compiles global.css for each platform
// and writes the theme names into uniwind-types.d.ts.
export default withUniwindConfig(
  // oxlint-disable-next-line unicorn/prefer-module -- Expo compiles this file to CommonJS; import.meta would make Node reload it as ESM and fail
  getDefaultConfig(__dirname),
  { cssEntryFile: './global.css', dtsFile: './uniwind-types.d.ts' },
);
`;

// What Uniwind writes for the default light and dark themes, seeded so
// \`className\` typechecks before Metro first runs. Metro rewrites it when
// the themes change.
const uniwindTypes = `// NOTE: This file is generated by uniwind and it should not be edited manually.
/// <reference types="uniwind/types" />

declare module 'uniwind' {
    export interface UniwindConfig {
        themes: readonly ['light', 'dark']
    }
}

export {}
`;

const layoutSource = `import '../global.css';

import { Stack } from 'expo-router';

const RootLayout = () => <Stack />;

export default RootLayout;
`;

// With a shared theme the starter uses its tokens; without one, Tailwind's
// palette.
const indexSource = (themed: boolean) => {
  const [screen, title] = themed
    ? ['bg-background', 'text-foreground']
    : ['bg-white dark:bg-neutral-950', 'text-neutral-950 dark:text-white'];
  return `import { Stack } from 'expo-router';
import { Text, View } from 'react-native';

import { greeting } from '../src/greeting.ts';

const Home = () => (
  <View className="flex-1 items-center justify-center ${screen}">
    <Stack.Screen options={{ title: 'Home' }} />
    <Text className="text-2xl font-semibold ${title}">{greeting('world')}</Text>
  </View>
);

export default Home;
`;
};

const greetingSource = `export const greeting = (name: string) => \`Hello, \${name}!\`;
`;

const testSource = `import { describe, expect, it } from 'vitest';

import { greeting } from '../src/greeting.ts';

describe('greeting', () => {
  it('greets by name', () => {
    expect(greeting('Ada')).toBe('Hello, Ada!');
  });
});
`;

// Expo's base config is the one RN type resolution needs (`react-native`
// export condition, `module: preserve`), so it replaces the shared base; the
// strictness flags shoemaker cares about are restated on top of it.
// expo/types declares CSS imports (the layout imports global.css); Expo
// otherwise reaches it only through expo-env.d.ts, which `expo start` writes
// and git ignores, so a fresh checkout would fail typecheck.
const tsconfig = (dir: string) =>
  ownedJson(`${dir}/tsconfig.json`, {
    extends: 'expo/tsconfig.base',
    compilerOptions: {
      strict: true,
      exactOptionalPropertyTypes: true,
      noUncheckedIndexedAccess: true,
      noImplicitOverride: true,
      noUnusedLocals: true,
      noFallthroughCasesInSwitch: true,
      verbatimModuleSyntax: true,
      allowImportingTsExtensions: true,
      types: ['node', 'expo/types'],
    },
    include: [
      '**/*.ts',
      '**/*.tsx',
      '*.mts',
      '.expo/types/**/*.ts',
      'expo-env.d.ts',
    ],
  });

export const expoApp = (ctx: GenContext, app: App): Contribution => {
  const dir = appDir(app);
  const base: Contribution = {
    files: [
      workspacePackageJson(ctx, {
        dir,
        name: app.name,
        // Metro and the Expo CLI load this package as CommonJS.
        module: false,
        sharedTsconfig: false,
        scripts: {
          dev: 'expo start',
          // `expo prebuild` rewrites exactly `expo start --ios` / `--android`
          // to `expo run:*`; the short flags keep these as sync wrote them.
          ios: 'expo start -i',
          android: 'expo start -a',
          clean: 'rm -rf .expo .turbo',
          ...(app.androidRelease === undefined
            ? {}
            : { 'build:apk': apkScript }),
        },
        dependencies,
        devDependencies,
        workspaceDependencies: themeDependency(ctx),
        extra: { main: 'expo-router/entry' },
      }),
      tsconfig(dir),
      vitestConfig(dir, { extension: 'mts' }),
      owned(`${dir}/metro.config.ts`, metroConfig),
      seed(`${dir}/app.config.ts`, appConfig(app)),
      seed(`${dir}/app/_layout.tsx`, layoutSource),
      seed(`${dir}/app/index.tsx`, indexSource(hasTheme(ctx.config))),
      seed(`${dir}/global.css`, appStylesheet(ctx, 'native')),
      seed(`${dir}/uniwind-types.d.ts`, uniwindTypes),
      seed(`${dir}/src/greeting.ts`, greetingSource),
      seed(`${dir}/test/greeting.test.ts`, testSource),
      seed(
        `${dir}/README.md`,
        `# ${ctx.pkg(app.name)}\n\nExpo Router app. \`bun run dev\` starts Metro; \`bun run ios\` / \`bun run android\` open a simulator.\n${app.androidRelease === undefined ? '' : androidReleaseReadme(ctx, app)}`,
      ),
    ],
    tasks: Arr.map(['ios', 'android'], (name) => ({
      name,
      package: ctx.pkg(app.name),
      persistent: true,
      cache: false,
    })),
    catalog: catalogOf(dependencies, devDependencies),
    gitignore: ['.expo/', 'expo-env.d.ts'],
    ignore: [`${dir}/uniwind-types.d.ts`],
  };
  return app.androidRelease === undefined
    ? base
    : mergeContributions([base, androidRelease(ctx, app, app.androidRelease)]);
};

export const expoGenerator = forApps('expo', expoApp);
