import { assert, describe, it } from '@effect/vitest';
import { Effect } from 'effect';

import { addEnvrc } from '../../src/migrations/add-envrc.ts';
import { catalogCheckToShoebox } from '../../src/migrations/catalog-check-to-shoebox.ts';
import { nixFmtScriptToShoebox } from '../../src/migrations/nix-fmt-script-to-shoe-box.ts';
import { oxfmtrcToTs } from '../../src/migrations/oxfmtrc-to-ts.ts';
import { turboJsonToJsonc } from '../../src/migrations/turbo-json-to-jsonc.ts';
import { json, pkgIn, plan } from './helpers.ts';

describe('oxfmtrc-to-ts', () => {
  it.effect(
    'keeps the stylesheet and repo-specific ignores, notes dropped options',
    () =>
      Effect.gen(function* () {
        const { applies, file } = yield* plan(oxfmtrcToTs, {
          'package.json': json({
            name: 'demo',
            scripts: {
              'oxfmt:check': 'oxfmt --check .',
              'oxfmt:fix': 'oxfmt -c .oxfmtrc.jsonc --write .',
            },
          }),
          '.oxfmtrc.jsonc': `{
  "singleQuote": true,
  "printWidth": 100,
  "experimentalTailwindcss": { "stylesheet": "./apps/web/src/styles.css" },
  "ignorePatterns": [
    "**/*.md",
    // generated by paraglide
    "apps/web/src/paraglide/**",
  ],
}
`,
        });
        assert.isTrue(applies);
        const config = file('oxfmt.config.ts') ?? '';
        assert.include(
          config,
          "import { defineShoeboxFormat } from 'shoe-box-oxfmt-config';",
        );
        assert.include(
          config,
          "tailwindStylesheet: './apps/web/src/styles.css',",
        );
        assert.include(
          config,
          "    // generated by paraglide\n    'apps/web/src/paraglide/**',",
        );
        assert.notInclude(config, "'**/*.md'");
        assert.include(config, '//   printWidth: 100');
        assert.notInclude(config, 'singleQuote');
        assert.isUndefined(file('.oxfmtrc.jsonc'));
        const scripts = pkgIn(file('package.json')).scripts;
        assert.strictEqual(
          scripts['oxfmt:check'],
          'oxfmt -c oxfmt.config.ts --check .',
        );
        assert.strictEqual(
          scripts['oxfmt:fix'],
          'oxfmt -c oxfmt.config.ts --write .',
        );
        assert.strictEqual(
          pkgIn(file('package.json')).devDependencies['shoe-box-oxfmt-config'],
          '^0.1.0',
        );
      }),
  );
});

describe('turbo-json-to-jsonc', () => {
  it.effect(
    'renames every turbo.json, skipping dirs that already have turbo.jsonc',
    () =>
      Effect.gen(function* () {
        const { changes } = yield* plan(turboJsonToJsonc, {
          'turbo.json': '{"tasks":{}}',
          'apps/api/turbo.json': '{"extends":["//"]}',
          'apps/web/turbo.json': '{}',
          'apps/web/turbo.jsonc': '{}',
        });
        assert.deepStrictEqual(changes, [
          { path: 'apps/api/turbo.jsonc', content: '{"extends":["//"]}' },
          { path: 'apps/api/turbo.json', content: undefined },
          { path: 'turbo.jsonc', content: '{"tasks":{}}' },
          { path: 'turbo.json', content: undefined },
        ]);
      }),
  );
});

describe('add-envrc', () => {
  it.effect('creates or prepends `use flake` when a flake exists', () =>
    Effect.gen(function* () {
      assert.strictEqual(
        (yield* plan(addEnvrc, { 'flake.nix': '{}' })).file('.envrc'),
        'use flake\n',
      );
      assert.strictEqual(
        (yield* plan(addEnvrc, {
          'flake.nix': '{}',
          '.envrc': 'export A=1\n',
        })).file('.envrc'),
        'use flake\nexport A=1\n',
      );
      assert.isFalse(
        (yield* plan(addEnvrc, { 'flake.nix': '{}', '.envrc': 'use flake\n' }))
          .applies,
      );
      assert.isFalse((yield* plan(addEnvrc, {})).applies);
    }),
  );
});

describe('catalog-check-to-shoebox', () => {
  it.effect('deletes the copy and points scripts at shoebox', () =>
    Effect.gen(function* () {
      const { file } = yield* plan(catalogCheckToShoebox, {
        'package.json': json({
          name: 'demo',
          workspaces: { packages: [], catalog: { effect: '4.0.6' } },
          scripts: {
            'catalog:check': 'bun scripts/lint/catalog-check.ts',
            'catalog:fix': 'bun scripts/lint/catalog-check.ts --fix',
          },
        }),
        'scripts/lint/catalog-check.ts': '// copy',
      });
      assert.isUndefined(file('scripts/lint/catalog-check.ts'));
      const root = pkgIn(file('package.json'));
      assert.deepStrictEqual(root.scripts, {
        'catalog:check': 'shoe-box check catalog',
        'catalog:fix': 'shoe-box check catalog --fix',
      });
      assert.strictEqual(root.catalog['shoe-box'], '^0.1.0');
      assert.strictEqual(root.devDependencies['shoe-box'], 'catalog:');
    }),
  );
});

describe('nix-fmt-script-to-shoe-box', () => {
  it.effect('deletes the bash script and points scripts at the CLI', () =>
    Effect.gen(function* () {
      const { applies, file } = yield* plan(nixFmtScriptToShoebox, {
        'package.json': json({
          name: 'demo',
          workspaces: { packages: [], catalog: { effect: '4.0.6' } },
          scripts: {
            'nix:fmt:check': './scripts/lint/nix-fmt.sh flake.nix -- -c',
            'nix:fmt:fix': './scripts/lint/nix-fmt.sh flake.nix',
            'fmt:all': 'bash scripts/lint/nix-fmt.sh -- -c flake.nix && oxfmt',
            build: 'tsc ',
          },
        }),
        'scripts/lint/nix-fmt.sh': '#!/usr/bin/env bash\n',
      });
      assert.isTrue(applies);
      assert.isUndefined(file('scripts/lint/nix-fmt.sh'));
      const root = pkgIn(file('package.json'));
      assert.deepStrictEqual(root.scripts, {
        'nix:fmt:check': 'shoe-box check nix-fmt',
        'nix:fmt:fix': 'shoe-box check nix-fmt --fix',
        'fmt:all': 'shoe-box check nix-fmt && oxfmt',
        build: 'tsc ',
      });
      assert.strictEqual(root.devDependencies['shoe-box'], 'catalog:');
    }),
  );

  it.effect('does not apply without the script', () =>
    Effect.gen(function* () {
      const { applies } = yield* plan(nixFmtScriptToShoebox, {
        'package.json': json({ name: 'demo' }),
      });
      assert.isFalse(applies);
    }),
  );
});
